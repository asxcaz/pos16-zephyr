#!/usr/bin/env bash
# PixelOS Android 16 QPR2 build helper for realme GT Neo 3 / zephyr.
# Run via crave run against Crave's pre-synced PixelOS project.
set -Ee -o pipefail

log() { printf '[pos16-zephyr] %s\n' "$*"; }
die() { printf '[pos16-zephyr] ERROR: %s\n' "$*" >&2; exit 1; }
handle_error() {
  local rc=$?
  local line="${BASH_LINENO[0]:-unknown}"
  printf "[pos16-zephyr] ERROR: line %s exited with status %s\n" "$line" "$rc" >&2
  exit "$rc"
}
trap handle_error ERR

if [ "$#" -gt 0 ] && [ "$1" = "--help" ]; then
  cat <<'HELP'
Build PixelOS Android 16 QPR2 for realme GT Neo 3 (zephyr) in a pre-synced Crave PixelOS workspace.
This script requires an existing .repo checkout. It re-pins that checkout to the official PixelOS sixteen-qpr2 manifest branch, then incrementally syncs existing projects in place.
It does not create a fresh source checkout and never uses --clean or --force-sync.
The script fetches the public device-specific vendor tree from the project's documented GitLab repository when it is not already present.
The vendor branch defaults to lineage-23.2; set POS16_VENDOR_BRANCH to override it.
Set POS16_CHECK_ONLY=1 to sync device dependencies, prepare Vendor, and check prerequisites without starting a ROM build.
HELP
  exit 0
fi

# Find the existing Android source root without initializing a new checkout.
ROOT="$(pwd)"
while [ "$ROOT" != "/" ] && [ ! -f "$ROOT/build/envsetup.sh" ]; do
  ROOT="$(dirname "$ROOT")"
done
[ -f "$ROOT/build/envsetup.sh" ] || die "Could not find build/envsetup.sh above the current directory. Submit this via crave run from the existing PixelOS project, not from an empty script-repository workspace."
[ -d "$ROOT/.repo" ] || die "No .repo directory found. Refusing to initialize or clone a fresh PixelOS source tree."
command -v repo >/dev/null 2>&1 || die "repo command is missing in the Crave build job."
command -v git >/dev/null 2>&1 || die "git is missing in the Crave build job."
command -v python3 >/dev/null 2>&1 || die "python3 is missing in the Crave build job."

cd "$ROOT"
DEVICE_DIR="$ROOT/device/oplus/zephyr"
MANIFEST_DIR="$ROOT/.repo/local_manifests"
MANIFEST_FILE="$MANIFEST_DIR/pos16-zephyr.xml"
MANIFEST_URL="https://github.com/PixelOS-AOSP/android_manifest.git"
MANIFEST_BRANCH="sixteen-qpr2"

# Revert only files previously generated by this script, so reruns remain idempotent.
if [ -f "$DEVICE_DIR/AndroidProducts.mk" ] && grep -q 'POS16_ZEPHYR_AUTOGENERATED' "$DEVICE_DIR/AndroidProducts.mk"; then
  git -C "$DEVICE_DIR" checkout -- AndroidProducts.mk
fi
if [ -f "$DEVICE_DIR/custom_zephyr.mk" ] && grep -q 'POS16_ZEPHYR_AUTOGENERATED' "$DEVICE_DIR/custom_zephyr.mk"; then
  rm -f "$DEVICE_DIR/custom_zephyr.mk"
fi

mkdir -p "$MANIFEST_DIR"
cat > "$MANIFEST_FILE" <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<manifest>
    <remote name="zephyr" fetch="https://github.com/oplus-mt6895" />
    <remote name="zephyr-kernel" fetch="https://gitlab.com/NINJAHUNTER1357" />

    <project name="android_device_oplus_zephyr"
             path="device/oplus/zephyr"
             remote="zephyr"
             revision="lineage-23.2" />
    <project name="android_device_oplus_zephyr-kernel"
             path="device/oplus/zephyr-kernel"
             remote="zephyr-kernel"
             revision="los-23.2" />
    <project name="android_hardware_mediatek"
             path="hardware/mediatek"
             remote="zephyr"
             revision="lineage-23.2" />
    <project name="android_hardware_oplus"
             path="hardware/oplus"
             remote="zephyr"
             revision="lineage-23.2" />
    <project name="android_device_mediatek_sepolicy_vndr"
             path="device/mediatek/sepolicy_vndr"
             remote="zephyr"
             revision="lineage-23.2" />
</manifest>
XML

log "Using existing Crave PixelOS source at: $ROOT"
log "Pinning the existing checkout to PixelOS manifest branch $MANIFEST_BRANCH; no clean or fresh checkout."
# Re-point the existing repo client at the intended manifest branch. Existing project
# checkouts and Git objects are reused; repo init here does not re-clone the source tree.
repo init -u "$MANIFEST_URL" -b "$MANIFEST_BRANCH"
log "Incrementally syncing the existing PixelOS projects plus the zephyr local-manifest projects."
# No project paths means all projects in the manifest are brought up to their pinned revisions.
# -c/--no-tags/--optimized-fetch limit unnecessary history; no clean/force-sync is used.
repo sync -c --no-tags --optimized-fetch --prune -j4

[ -f "$DEVICE_DIR/lineage_zephyr.mk" ] || die "The lineage-23.2 zephyr device tree did not sync correctly."
KERNEL_DIR="$ROOT/device/oplus/zephyr-kernel"
[ -s "$KERNEL_DIR/Image.gz" ] || die "The prebuilt kernel Image.gz is missing or empty."
[ -s "$KERNEL_DIR/dtb/mt6895.dtb" ] || die "The prebuilt MT6895 DTB is missing or empty."

# BoardConfig.mk reads these module lists and packages every module named in them.
for module_list in \
  modules/vendor_dlkm.modules.load \
  modules/vendor_ramdisk.modules.load \
  modules/vendor_ramdisk.modules.load.recovery
do
  [ -s "$KERNEL_DIR/$module_list" ] || die "Required kernel module list is missing or empty: $module_list"
  while IFS= read -r module || [ -n "$module" ]; do
    module="$(printf '%s' "$module" | sed 's/#.*//; s/^[[:space:]]*//; s/[[:space:]]*$//')"
    [ -n "$module" ] || continue
    [ -s "$KERNEL_DIR/modules/$module" ] || die "Kernel module listed in $module_list is missing or empty: modules/$module"
  done < "$KERNEL_DIR/$module_list"
done

# These modules are referenced explicitly by the device BoardConfig in addition to the lists.
for module in \
  bt_drv_6895.ko \
  connfem.ko \
  conninfra.ko \
  fmradio_drv_connac2x.ko \
  gps_drv_dl_v050.ko \
  gps_pwr.ko \
  gps_scp.ko \
  wlan_drv_gen4m_6895.ko \
  wmt_chrdev_wifi_connac2.ko
do
  [ -s "$KERNEL_DIR/modules/$module" ] || die "Explicitly required kernel module is missing or empty: modules/$module"
done

# The organization README lists this GitLab project as the required Vendor tree.
# Clone to the path inherited by device.mk and BoardConfig.mk; do not put blobs
# in this public build-helper repository.
VENDOR_DIR="$ROOT/vendor/oplus/zephyr"
VENDOR_REPO_URL="https://gitlab.com/NINJAHUNTER1357/proprietary_vendor_oplus_zephyr.git"
VENDOR_MK="$VENDOR_DIR/zephyr-vendor.mk"
VENDOR_BOARD_MK="$VENDOR_DIR/BoardConfigVendor.mk"

if [ -f "$VENDOR_MK" ] && [ -f "$VENDOR_BOARD_MK" ]; then
  log "Using existing Vendor tree at vendor/oplus/zephyr."
elif [ -e "$VENDOR_DIR" ]; then
  die "vendor/oplus/zephyr already exists but is missing zephyr-vendor.mk and/or BoardConfigVendor.mk; refusing to overwrite an existing directory. Repair or move it, then rerun."
else
  mkdir -p "$ROOT/vendor/oplus"
  VENDOR_TMP_ROOT="$(mktemp -d "$ROOT/vendor/oplus/.zephyr-vendor.XXXXXX")"
  VENDOR_TMP="$VENDOR_TMP_ROOT/repo"

  VENDOR_BRANCH="${POS16_VENDOR_BRANCH:-lineage-23.2}"
  log "Cloning Vendor tree from GitLab branch: $VENDOR_BRANCH"
  if ! git clone --depth=1 --single-branch --branch "$VENDOR_BRANCH" "$VENDOR_REPO_URL" "$VENDOR_TMP"; then
    rm -rf "$VENDOR_TMP_ROOT"
    die "Could not clone Vendor tree branch '$VENDOR_BRANCH' from $VENDOR_REPO_URL"
  fi

  if [ ! -f "$VENDOR_TMP/zephyr-vendor.mk" ] || [ ! -f "$VENDOR_TMP/BoardConfigVendor.mk" ]; then
    rm -rf "$VENDOR_TMP_ROOT"
    die "The cloned Vendor tree does not contain the required zephyr-vendor.mk and BoardConfigVendor.mk files at its root. Check the GitLab default branch or set POS16_VENDOR_BRANCH."
  fi

  mv "$VENDOR_TMP" "$VENDOR_DIR"
  rmdir "$VENDOR_TMP_ROOT"
  log "Vendor tree installed at vendor/oplus/zephyr (branch: $(git -C "$VENDOR_DIR" branch --show-current))."
fi

[ -f "$VENDOR_MK" ] || die "Required vendor makefile is missing: vendor/oplus/zephyr/zephyr-vendor.mk"
[ -f "$VENDOR_BOARD_MK" ] || die "Required vendor board config is missing: vendor/oplus/zephyr/BoardConfigVendor.mk"

if [ "${POS16_CHECK_ONLY:-0}" = "1" ]; then
  vendor_file_count="$(find "$ROOT/vendor/oplus/zephyr" -type f -print | wc -l | tr -d '[:space:]')"
  log "Vendor preflight passed: required makefiles found; vendor/oplus/zephyr contains ${vendor_file_count} files."
  log "POS16_CHECK_ONLY=1: stopping before product-file changes, IMS cloning, patches, or Android compilation."
  exit 0
fi

# Make the LineageOS device product discoverable by PixelOS vendor/custom config.
cp "$DEVICE_DIR/lineage_zephyr.mk" "$DEVICE_DIR/custom_zephyr.mk"
sed -i 's@vendor/lineage/config/common_full_phone.mk@vendor/custom/config/common_full_phone.mk@' "$DEVICE_DIR/custom_zephyr.mk"
sed -i 's/PRODUCT_NAME := lineage_zephyr/PRODUCT_NAME := custom_zephyr/' "$DEVICE_DIR/custom_zephyr.mk"
TMP_PRODUCT="$DEVICE_DIR/custom_zephyr.mk.tmp"
{ printf '%s\n' '# POS16_ZEPHYR_AUTOGENERATED - managed by pos16-zephyr build.sh'; cat "$DEVICE_DIR/custom_zephyr.mk"; } > "$TMP_PRODUCT"
mv "$TMP_PRODUCT" "$DEVICE_DIR/custom_zephyr.mk"
cat > "$DEVICE_DIR/AndroidProducts.mk" <<'PRODUCTS'
# POS16_ZEPHYR_AUTOGENERATED - managed by pos16-zephyr build.sh
PRODUCT_MAKEFILES := \
    $(LOCAL_DIR)/custom_zephyr.mk

COMMON_LUNCH_CHOICES := \
    custom_zephyr-bp4a-userdebug
PRODUCTS

# Match the device tree's own vendorsetup.sh actions, skipping applied cherry-picks.
IMS_DIR="$ROOT/vendor/mediatek/ims"
IMS_URL="https://github.com/Adarsh0127-Elite/android_vendor_mediatek_ims.git"
IMS_BRANCH="android-16-qpr2"
if ! git -C "$IMS_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  [ ! -e "$IMS_DIR" ] || die "vendor/mediatek/ims exists but is not a valid Git checkout; refusing to overwrite it."
  mkdir -p "$ROOT/vendor/mediatek"
  log "Cloning Android 16 QPR2 MediaTek IMS dependency."
  git clone --depth=1 --single-branch -b "$IMS_BRANCH" "$IMS_URL" "$IMS_DIR"
else
  current_ims_url="$(git -C "$IMS_DIR" remote get-url origin)"
  [ "$current_ims_url" = "$IMS_URL" ] || die "Existing MediaTek IMS checkout has unexpected origin: $current_ims_url"
  git -C "$IMS_DIR" fetch --depth=1 origin "$IMS_BRANCH"
  git -C "$IMS_DIR" checkout -B "$IMS_BRANCH" FETCH_HEAD
fi
[ -s "$IMS_DIR/ims.mk" ] || die "Required MediaTek IMS makefile is missing: vendor/mediatek/ims/ims.mk"

apply_patch_if_applicable() {
  local repo_dir="$1"
  local patch_url="$2"
  local label="$3"
  local patch_file
  git -C "$repo_dir" rev-parse --is-inside-work-tree >/dev/null 2>&1 || die "Expected git project not found: $repo_dir"
  patch_file="$(mktemp)"
  if ! curl -fLsS --retry 3 "$patch_url" -o "$patch_file"; then
    rm -f "$patch_file"
    log "WARNING: Could not download optional compatibility patch: $label"
    return 0
  fi

  # Use a small patch file instead of fetching an entire framework repository's
  # commit ancestry (which can download hundreds of thousands of Git objects).
  if git -C "$repo_dir" apply --reverse --check "$patch_file" >/dev/null 2>&1; then
    log "Patch already applied: $label"
    rm -f "$patch_file"
    return 0
  fi
  if git -C "$repo_dir" apply --check "$patch_file" >/dev/null 2>&1; then
    git -C "$repo_dir" apply "$patch_file"
    log "Applied patch: $label"
  else
    log "WARNING: Patch does not apply cleanly to this PixelOS revision; skipped optional enhancement: $label"
  fi
  rm -f "$patch_file"
}

apply_patch_if_applicable "$ROOT/packages/apps/Aperture" \
  https://github.com/Adarsh0127-Elite/android_packages_apps_Aperture/commit/9509277efc852ad8bdcce204e0d9cfe104b6d190.patch \
  "Aperture MediaTek 60 FPS support"

# Full repo sync above updates the Crave-provided older base to the pinned
# PixelOS sixteen-qpr2 manifest before these patches are tested. A shallow clone
# of that branch confirmed both patches apply cleanly; always apply the parent first.
apply_patch_if_applicable "$ROOT/frameworks/native" \
  https://github.com/oplus-mt6895/android_frameworks_native/commit/5ae7b13cc9e7359261d15ab185ee4aaeb512f754.patch \
  "MediaTek GED-KPI support (gpufreq)"

apply_patch_if_applicable "$ROOT/frameworks/native" \
  https://github.com/oplus-mt6895/android_frameworks_native/commit/31f62caf1160bb8460eb7f7c66e279fdb51867d6.patch \
  "MediaTek UDFPS dither support"

apply_patch_if_applicable "$ROOT/frameworks/base" \
  https://github.com/oplus-mt6895/android_frameworks_base/commit/8fdf7742a1adabcb5c79fd23dcf2039fcda6ce3b.patch \
  "MediaTek UDFPS GHBM support"

log "Loading PixelOS build environment."
source "$ROOT/build/envsetup.sh"
cd "$ROOT"
lunch custom_zephyr-bp4a-userdebug

JOBS="${POS16_JOBS:-$(nproc --all 2>/dev/null || nproc)}"
log "Starting PixelOS build with $JOBS jobs."
m -j"$JOBS" pixelos

PRODUCT_OUT="$ROOT/out/target/product/zephyr"
if [ -d "$PRODUCT_OUT" ]; then
  log "Build output files:"
  find "$PRODUCT_OUT" -maxdepth 1 -type f \( -name '*.zip' -o -name '*.img' \) -printf '%f (%s bytes)\n' | sort || true
else
  log "Build command finished, but the expected product output directory was not found: $PRODUCT_OUT"
fi
log "Finished. Use the Crave job page/logs to verify the final build result and artifacts."
